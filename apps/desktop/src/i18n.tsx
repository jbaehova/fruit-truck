export type MessageKey = keyof typeof messages.en;
type Variables = Record<string, string | number>;

type I18nValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey, variables?: Variables) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(message: string, variables?: Variables) {
  if (!variables) return message;
  return message.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(variables, key) ? String(variables[key]) : match,
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() =>
    typeof localStorage !== "undefined" && localStorage.getItem(STORAGE_KEY) === "ko" ? "ko" : "en",
  );

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === "ko" ? "ko-KR" : "en-US",
    setLanguage,
    t: (key, variables) => interpolate(messages[language][key], variables),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

// oxlint-disable-next-line react/only-export-components
export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
